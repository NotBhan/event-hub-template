/**
 * One-off build helper: self-host the two web fonts.
 *
 * Downloads only the Latin subset from Google Fonts and rewrites the CSS to point
 * at local files. Self-hosting avoids a third-party request on every page view,
 * which matters for both performance and privacy in a client deployment.
 *
 * Run once; the output is committed. Not part of the application build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename } from 'node:path';

const css = readFileSync('/tmp/fonts.css', 'utf8');
const blocks = css.split('@font-face').slice(1);

const kept: { family: string; weight: string; style: string; url: string; display: string }[] = [];

for (const block of blocks) {
  // Latin only: the other subsets (cyrillic, greek, vietnamese) triple the payload.
  const isLatin = /unicode-range:[^;]*U\+0000-00FF/.test(block);
  if (!isLatin) continue;

  const family = /font-family:\s*'([^']+)'/.exec(block)?.[1];
  const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1]?.trim();
  const style = /font-style:\s*([^;]+);/.exec(block)?.[1]?.trim();
  const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
  const display = /font-display:\s*([^;]+);/.exec(block)?.[1]?.trim();

  if (!family || !weight || !url) continue;

  kept.push({ family, weight, style: style ?? 'normal', url, display: display ?? 'swap' });
}

mkdirSync('public/fonts', { recursive: true });

const output: string[] = [
  '/* Self-hosted webfonts — Latin subset only.',
  ' * Generated by scripts/fetch-fonts.ts. Regenerate only if the families change. */',
  '',
];

for (const font of kept) {
  const slug = `${font.family.toLowerCase().replace(/\s+/g, '-')}-${font.weight.replace(/\s+/g, '-')}-${font.style}`;
  const filename = `${slug}.woff2`;

  const response = await fetch(font.url);
  if (!response.ok) throw new Error(`Failed to download ${font.url}: ${response.status}`);

  const buffer = Buffer.from(await response.arrayBuffer());
  writeFileSync(`public/fonts/${filename}`, buffer);

  output.push(
    '@font-face {',
    `  font-family: '${font.family}';`,
    `  font-style: ${font.style};`,
    `  font-weight: ${font.weight};`,
    `  font-display: ${font.display};`,
    `  src: url('/fonts/${filename}') format('woff2');`,
    '  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA,',
    '    U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193,',
    '    U+2212, U+2215, U+FEFF, U+FFFD;',
    '}',
    '',
  );

  console.log(`  ${filename}  (${(buffer.length / 1024).toFixed(1)} kB)`);
}

writeFileSync('src/styles/fonts.css', `${output.join('\n').trimEnd()}\n`);

console.log(`\nWrote src/styles/fonts.css with ${kept.length} face(s).`);
void basename;
